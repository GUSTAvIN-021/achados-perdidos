
CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    matricula VARCHAR(30) UNIQUE,
    telefone VARCHAR(20)
);

CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    descricao VARCHAR(255)
);

CREATE TABLE local (
    id_local INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    bloco VARCHAR(50),
    descricao VARCHAR(255)
);

CREATE TABLE objeto (
    id_objeto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    data_ocorrencia DATE NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PERDIDO', 'ENCONTRADO', 'DEVOLVIDO')),

    id_usuario INTEGER NOT NULL,
    id_categoria INTEGER NOT NULL,
    id_local INTEGER NOT NULL,

    CONSTRAINT fk_objeto_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario),

    CONSTRAINT fk_objeto_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categoria(id_categoria),

    CONSTRAINT fk_objeto_local
        FOREIGN KEY (id_local)
        REFERENCES local(id_local)
);
